import fs from 'node:fs';
import path from 'node:path';
import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';
import tailwindcss from '@tailwindcss/vite';

const DOCS_FONTS = path.resolve(import.meta.dirname, '../docs/fonts');

// Dev only: the reading face (Source Serif 4) is self-hosted in docs/fonts and
// served at /fonts/* in production (scripts/prepare-deploy.mjs copies it into
// dist). publicDir can only be one directory, so the dev server gets a tiny
// read-only route for the same URLs. The CSS references the fonts by their
// runtime URL (/fonts/...), never through the bundler, so the preload in
// index.html and the @font-face in src/index.css always name one file.
function docsFonts() {
    return {
        name: 'plaincast-docs-fonts',
        apply: 'serve',
        configureServer(server) {
            server.middlewares.use('/fonts', (req, res, next) => {
                const name = decodeURIComponent((req.url || '').split('?')[0]).replace(/^\/+/, '');
                if (!/^[a-z0-9-]+\.woff2$/i.test(name)) return next();
                const file = path.join(DOCS_FONTS, name);
                if (!fs.existsSync(file)) return next();
                res.setHeader('Content-Type', 'font/woff2');
                fs.createReadStream(file).pipe(res);
            });
        },
    };
}

// Dev only, opt-in: PLAINCAST_DEV_API=https://plaincast.live bun run dev
// proxies GET /api/* (conditions, changelog, translate-issuance) to a deployed
// site so the layout can be checked against real AI text. Anything else
// (POST /api/translate) gets a 404 here and soft-falls back like an outage.
const DEV_API = process.env.PLAINCAST_DEV_API;

// The app imports the canonical data modules from ../docs/js (glossary,
// offices, abbreviations, timeline) — single source of truth, so allow the
// dev server to reach one level above this package root.
export default defineConfig({
    plugins: [react(), tailwindcss(), docsFonts()],
    resolve: {
        alias: {
            '@': path.resolve(import.meta.dirname, './src'),
            '@data': path.resolve(import.meta.dirname, '../docs/js'),
        },
    },
    server: {
        fs: { allow: ['..'] },
        proxy: DEV_API
            ? {
                '/api': {
                    target: DEV_API,
                    changeOrigin: true,
                    bypass: (req) => (req.method === 'GET' || req.method === 'HEAD' ? undefined : false),
                },
            }
            : undefined,
    },
    build: {
        // dist/.vite/manifest.json: scripts/prepare-deploy.mjs reads it to
        // map the committed shell's placeholder names to this build's files,
        // then deletes it (it is not part of the deployed site).
        manifest: true,
        rollupOptions: {
            output: {
                // Content-hashed names, served `immutable` (vercel.json). The
                // committed shell (api/_home-shell.html, generated by
                // scripts/build-offices.mjs) cannot know a per-build hash, so it
                // keeps the PLACEHOLDER names /assets/app.css, /assets/vendor.js
                // and /assets/app.js; scripts/prepare-deploy.mjs rewrites them
                // to these files in the Vercel build checkout, before the
                // functions are bundled. The placeholders are the names below
                // with the `-[hash]` removed. There is exactly one URL for the
                // app entry per deployment (no stable-named copy, no ?v=), so
                // the on-demand chunks' `import … from "./app-<hash>.js"` reuses
                // the page's module instead of evaluating the app twice.
                // On-demand chunks (ChangelogView, KbdDialog, sonner, diff —
                // named after the module App.jsx and lib/toast.js import) only
                // ever import files of their own build, so the old
                // cross-build pairing guard (minifyInternalExports: false) is
                // gone.
                entryFileNames: 'assets/app-[hash].js',
                chunkFileNames: 'assets/[name]-[hash].js',
                assetFileNames: (info) => {
                    const name = info.names?.[0] || info.name || '';
                    return name.endsWith('.css') ? 'assets/app-[hash].css' : 'assets/[name]-[hash][extname]';
                },
                // Vendor split: the framework and the component primitives
                // change far less often than the app code, so returning
                // visitors keep them cached across deploys.
                // @radix-ui/react-dialog is deliberately absent: only the
                // on-demand shortcuts dialog uses it, so it ships in that
                // chunk (assets/KbdDialog.js), not on first load.
                manualChunks: {
                    vendor: [
                        'react',
                        'react-dom',
                        '@radix-ui/react-accordion',
                        '@radix-ui/react-progress',
                        '@radix-ui/react-select',
                        '@radix-ui/react-separator',
                        '@radix-ui/react-slot',
                        '@radix-ui/react-tabs',
                        '@radix-ui/react-tooltip',
                    ],
                },
            },
        },
    },
});
