// Writes Plaincast's office data modules from the committed NOAA/NWS
// snapshots — offline and deterministic (same snapshots in, same bytes out):
//
//   docs/js/offices.js               the <generated:offices> block
//   shadcn/src/lib/offices-groups.js picker/footer region groups
//   api/_climate-normals.js          "Normal high" table for /api/conditions
//
//   bun scripts/build-office-data.mjs          (then: bun scripts/build-offices.mjs)
//
// Refresh the snapshots first when NWS data may have moved:
//   bun scripts/fetch-office-data.mjs && bun scripts/fetch-climate-normals.mjs
//
// tests/offices-data.test.js fails if any generated file drifts from this.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { LEGACY, NAME_OVERRIDES, OFFICE_REGION_GROUPS } from './office-curation.mjs';
import { cityOfNwsName } from './fetch-office-data.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const PATHS = {
    officeSnapshot: join(ROOT, 'scripts', 'data', 'nws-offices.json'),
    normalsSnapshot: join(ROOT, 'scripts', 'data', 'climate-normals.json'),
    offices: join(ROOT, 'docs', 'js', 'offices.js'),
    groups: join(ROOT, 'shadcn', 'src', 'lib', 'offices-groups.js'),
    normals: join(ROOT, 'api', '_climate-normals.js'),
};
const BEGIN = '// <generated:offices>';
const END = '// </generated:offices>';

const q = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const round2 = (n) => Math.round(n * 100) / 100;

// One office's facts, from the snapshot + curation.
export function resolveOffices(snapshot) {
    const codes = Object.keys(snapshot.offices);
    // NWS city per office, for spotting shared city names ("Charleston").
    const nwsCity = Object.fromEntries(codes.map(c => {
        const o = snapshot.offices[c];
        return [c, cityOfNwsName(o.office?.name || o.location)];
    }));
    const out = {};
    for (const code of codes) {
        const o = snapshot.offices[code];
        const s = o.station;
        const state = o.office?.state || s.state;
        let name, alertState, sender;
        if (LEGACY[code]) {
            [name, alertState, sender] = LEGACY[code];
        } else {
            name = NAME_OVERRIDES[code];
            if (!name) {
                name = nwsCity[code];
                const shared = codes.some(c => c !== code && nwsCity[c] === nwsCity[code]);
                if (shared) name = `${name} ${state}`;
            }
            alertState = state;
            // The AFD's own "National Weather Service <City> <ST>" line: the
            // office names itself the same way in its alerts' senderName.
            sender = String(o.afd.headerName || nwsCity[code]).replace(/\s+/g, ' ').trim();
        }
        out[code] = {
            name, alertState, sender,
            timeZone: s.timeZone,
            coords: [round2(s.lat), round2(s.lon)],
            station: s.id,
            issuing: o.afd.issuingOffices[0],
        };
    }
    return out;
}

export function orderedGroups(resolved) {
    const seen = new Map();
    const groups = OFFICE_REGION_GROUPS.map(g => {
        for (const c of g.codes) {
            if (!resolved[c]) throw new Error(`group ${g.label} lists ${c}, which is not in the snapshot`);
            if (seen.has(c)) throw new Error(`${c} is in both ${seen.get(c)} and ${g.label}`);
            seen.set(c, g.label);
        }
        return { label: g.label, codes: [...g.codes].sort((a, b) => resolved[a].name.localeCompare(resolved[b].name, 'en')) };
    });
    const ungrouped = Object.keys(resolved).filter(c => !seen.has(c));
    if (ungrouped.length) throw new Error(`no region group for: ${ungrouped.join(', ')}`);
    return groups;
}

function table(name, comment, codes, value) {
    const lines = codes.map(c => `    ${q(c)}: ${value(c)},`);
    return `${comment}\nexport const ${name} = {\n${lines.join('\n')}\n};`;
}

export function renderOfficeBlock(snapshot) {
    const r = resolveOffices(snapshot);
    const codes = orderedGroups(r).flatMap(g => g.codes);
    const n = codes.length;
    const issuing = Object.keys(snapshot.issuingOffices).sort();
    return [
        BEGIN,
        '// GENERATED by scripts/build-office-data.mjs — do not edit by hand.',
        `// ${n} offices: every NWS office with an Area Forecast Discussion in the`,
        `// 7 days before ${snapshot.fetchedAt.slice(0, 10)} (api.weather.gov/products/types/AFD/locations).`,
        '// Facts come from scripts/data/nws-offices.json (fetched from api.weather.gov by',
        '// scripts/fetch-office-data.mjs); names and groups from scripts/office-curation.mjs.',
        `// Key order = picker order (region groups, then display name).`,
        '',
        table('OFFICE_NAMES', '// Display names. The 68 launch offices keep their original names.', codes, c => q(r[c].name)),
        '',
        table('OFFICE_TIMEZONES', "// IANA time zone of each office's primary observation station (/stations/<ID> timeZone).", codes, c => q(r[c].timeZone)),
        '',
        table('OFFICE_COORDS', "// [lat, lon] of each office's primary observation station (/stations/<ID> geometry).", codes, c => `[${r[c].coords.join(', ')}]`),
        '',
        table('OFFICE_STATIONS', "// Primary observation station (ICAO): /api/conditions reads \"Now\" from it, and its\n// NCEI normals are the \"Normal high\".", codes, c => q(r[c].station)),
        '',
        table('OFFICE_STATES', '// State or territory passed as ?area= to the NWS alerts API.', codes, c => q(r[c].alertState)),
        '',
        table('OFFICE_SENDER', "// Sender-name fragment of the office's alerts (fallback match when an alert has no\n// WMO heading). New offices: the AFD's \"National Weather Service <City> <ST>\" line.", codes, c => q(r[c].sender)),
        '',
        '// Issuing-office id → office code. National product lists and WMO headings',
        '// name an office by its 4-letter id (KOKX, PAFC, PHFO, PGUM, TJSJ, NSTU); each',
        "// pair is read from that office's own AFD list and cross-checked against the",
        '// national 7-day list (a mismatch fails the fetch).',
        `export const ISSUING_OFFICE_TO_CODE = {\n${issuing.map(id => `    ${q(id)}: ${q(snapshot.issuingOffices[id])},`).join('\n')}\n};`,
        END,
    ].join('\n');
}

export function renderOfficesJs(current, snapshot) {
    const a = current.indexOf(BEGIN);
    const b = current.indexOf(END);
    if (a < 0 || b < a) throw new Error(`docs/js/offices.js is missing the ${BEGIN} … ${END} markers`);
    return current.slice(0, a) + renderOfficeBlock(snapshot) + current.slice(b + END.length);
}

export function renderGroupsJs(snapshot) {
    const r = resolveOffices(snapshot);
    const groups = orderedGroups(r);
    const body = groups.map(g => {
        const codes = g.codes.map(q);
        const lines = [];
        for (let i = 0; i < codes.length; i += 8) lines.push(`        ${codes.slice(i, i + 8).join(', ')},`);
        return `    { label: ${q(g.label)}, codes: [\n${lines.join('\n')}\n    ] },`;
    }).join('\n');
    return `// GENERATED by scripts/build-office-data.mjs from scripts/office-curation.mjs
// — do not edit by hand. Region grouping for the office picker and the footer
// directory; codes sorted by display name (OFFICE_NAMES in docs/js/offices.js).

export const OFFICE_GROUPS = [
${body}
];
`;
}

export function renderNormalsJs(normalsSnapshot, snapshot) {
    const r = resolveOffices(snapshot);
    const codes = Object.keys(normalsSnapshot.normals).sort();
    for (const c of codes) {
        if (normalsSnapshot.normals[c].station !== r[c]?.station) {
            throw new Error(`${c}: normals are for ${normalsSnapshot.normals[c].station} but the office station is ${r[c]?.station}; re-run fetch-climate-normals`);
        }
    }
    const lines = codes.map(c => {
        const n = normalsSnapshot.normals[c];
        return `    ${q(c)}: [${n.tmaxF.join(', ')}], // ${n.station} = ${n.ghcnd} ${n.nceiName}`;
    });
    const missing = Object.entries(normalsSnapshot.missing).map(([c, m]) => `//   ${c} (${m.station}): ${m.reason}`);
    return `// GENERATED by scripts/build-office-data.mjs from scripts/data/climate-normals.json
// — do not edit by hand. Refresh: bun scripts/fetch-climate-normals.mjs.
//
// Monthly normal daily-maximum temperature (°F, rounded to whole degrees),
// Jan..Dec: NOAA NCEI 1991–2020 normals (normals-monthly-1991-2020,
// MLY-TMAX-NORMAL) at each office's primary observation station — the same
// station /api/conditions reads "Now" from (OFFICE_STATIONS).
// ${codes.length} of ${Object.keys(r).length} offices. No verified normal (the conditions strip hides the cell):
${missing.join('\n')}
export const CLIMATE_NORMALS = {
${lines.join('\n')}
};
`;
}

export function buildOfficeData() {
    const snapshot = JSON.parse(readFileSync(PATHS.officeSnapshot, 'utf8'));
    const normals = JSON.parse(readFileSync(PATHS.normalsSnapshot, 'utf8'));
    return {
        [PATHS.offices]: renderOfficesJs(readFileSync(PATHS.offices, 'utf8'), snapshot),
        [PATHS.groups]: renderGroupsJs(snapshot),
        [PATHS.normals]: renderNormalsJs(normals, snapshot),
    };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
    const files = buildOfficeData();
    for (const [path, text] of Object.entries(files)) writeFileSync(path, text);
    console.log(`Wrote ${Object.keys(files).length} office data files`);
}
